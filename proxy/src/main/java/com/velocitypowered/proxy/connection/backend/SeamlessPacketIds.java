/**
 * Per-protocol-version packet ids that seamless transfers need but Velocity does not decode.
 *
 * <p>The client and backend connections always share a protocol version in Velocity, so ids are
 * selected automatically from the connection's version. The table between the GENERATED markers
 * is produced by {@code scripts/seamless-packet-ids.py} from ViaVersion's packet enums — do not
 * edit it by hand. A version missing from the table is not eligible for seamless transfers (the
 * regular switch is used instead), and {@code SeamlessPacketIdsTest} fails the build while any
 * version Velocity supports is missing, so a new Minecraft release cannot silently degrade.</p>
 *
 * <p>The Respawn id is not part of the table: Velocity registers {@link RespawnPacket}
 * encode-only, so its id is looked up from {@link StateRegistry} and can never drift from
 * Velocity's own mapping.</p>
 */
