  /**
   * The packet ids of one protocol version.
   *
   * @param addEntity          clientbound Spawn Entity
   * @param addExperienceOrb   clientbound Spawn Experience Orb, or -1 (merged into Spawn Entity
   *                           since 1.21.5)
   * @param removeEntities     clientbound Remove Entities
   * @param chunkBatchFinished clientbound Chunk Batch Finished (the commit trigger)
   * @param gameEvent          clientbound Game Event
   * @param playerChat         clientbound Player Chat
   * @param respawn            clientbound Respawn (from {@link StateRegistry})
   * @param clientboundLayouts entity-id layout of each clientbound packet id
   * @param serverboundLayouts entity-id layout of each serverbound packet id
   */
  public record Table(int addEntity, int addExperienceOrb, int removeEntities,
                      int chunkBatchFinished, int gameEvent, int playerChat, int respawn,
                      byte[] clientboundLayouts, byte[] serverboundLayouts) {

    /**
     * Returns the entity-id layout of a clientbound packet.
     *
     * @param packetId the packet id
     * @return one of the {@code LAYOUT_*} constants
     */
    byte clientboundLayout(int packetId) {
      return layout(clientboundLayouts, packetId);
    }

    /**
     * Returns the entity-id layout of a serverbound packet.
     *
     * @param packetId the packet id
     * @return one of the {@code LAYOUT_*} constants
     */
    byte serverboundLayout(int packetId) {
      return layout(serverboundLayouts, packetId);
    }

    /**
     * Whether a packet spawns an entity on the client (Spawn Entity / Spawn Experience Orb).
     *
     * @param packetId the packet id
     * @return true for entity spawn packets
     */
    boolean isSpawn(int packetId) {
      return packetId == addEntity || (addExperienceOrb >= 0 && packetId == addExperienceOrb);
    }

    private static byte layout(byte[] layouts, int packetId) {
      return packetId >= 0 && packetId < layouts.length ? layouts[packetId] : LAYOUT_NONE;
    }
  }

  private static int[] ids(int... ids) {
    return ids;
  }

  private static void table(ProtocolVersion version, int addEntity, int addExperienceOrb,
      int removeEntities, int chunkBatchFinished, int gameEvent, int playerChat,
      int entityEvent, int setEntityLink, int takeItemEntity, int setPassengers,
      int[] clientboundLeadingId, int[] serverboundLeadingId) {
    final byte[] clientbound = new byte[256];
    for (int id : clientboundLeadingId) {
      clientbound[id] = LAYOUT_LEADING_VARINT;
    }
    clientbound[entityEvent] = LAYOUT_LEADING_INT;
    clientbound[setEntityLink] = LAYOUT_TWO_INTS;
    clientbound[takeItemEntity] = LAYOUT_TWO_VARINTS;
    clientbound[setPassengers] = LAYOUT_PASSENGERS;
    clientbound[removeEntities] = LAYOUT_VARINT_LIST;
    final byte[] serverbound = new byte[256];
    for (int id : serverboundLeadingId) {
      serverbound[id] = LAYOUT_LEADING_VARINT;
    }
    final int respawn = StateRegistry.PLAY
        .getProtocolRegistry(ProtocolUtils.Direction.CLIENTBOUND, version)
        .getPacketId(new RespawnPacket());
    TABLES.put(version, new Table(addEntity, addExperienceOrb, removeEntities, chunkBatchFinished,
        gameEvent, playerChat, respawn, clientbound, serverbound));
  }

  /**
   * Returns the packet id table of a protocol version.
   *
   * @param version the connection's protocol version
   * @return the table, or null if seamless transfers do not support this version
   */
  public static @Nullable Table forVersion(ProtocolVersion version) {
    return TABLES.get(version);
  }

  /**
   * Whether seamless transfers support a protocol version.
   *
   * @param version the connection's protocol version
   * @return true if the version's packet ids are known
   */
  public static boolean isSupported(ProtocolVersion version) {
    return TABLES.containsKey(version);
  }

  /**
   * Fingerprints the "Game Event: start waiting for chunks" packet (event 13, value 0.0f): the
   * payload is exactly [varint Game Event id][unsigned byte 13][float 0.0f].
   *
   * <p>On clients up to 1.21.1, this event unconditionally opens the "loading terrain" screen
   * (vanilla's {@code startWaitingForNewLevel} has no already-in-a-level check — the same flaw
   * kennytv's force-close-loading-screen mod patches client-side), and the screen closes on the
   * next tick when the player's render section is already compiled. Whether a frame renders in
   * between is luck — the intermittent one-frame flash on seamless transfers. Newer clients skip
   * the screen when the level is already loaded. The seamless path therefore drops this event
   * for the whole join sequence of the swapped backend: the shared world is pre-loaded by
   * precondition, so the screen serves no purpose there on any version.</p>
   *
   * @param buf   the raw packet, readerIndex at the packet id
   * @param table the connection's packet id table
   * @return true if this is the level-load-start game event
   */
  public static boolean isLevelLoadStartEvent(ByteBuf buf, Table table) {
    final int readerIndex = buf.readerIndex();
    if (peekVarInt(buf) != table.gameEvent()) {
      return false;
    }
    final int idLength = varIntLength(table.gameEvent());
    return buf.readableBytes() == idLength + 5
        && (buf.getByte(readerIndex + idLength) & 0xFF) == 13
        && buf.getInt(readerIndex + idLength + 1) == 0;
  }

  /**
   * Builds a Game Event packet.
   *
   * @param table the connection's packet id table
   * @param event the game event id
   * @param value the event's float parameter
   * @param alloc a buffer to write into
   * @return {@code alloc}, holding the packet
   */
  public static ByteBuf gameEvent(Table table, int event, float value, ByteBuf alloc) {
    ProtocolUtils.writeVarInt(alloc, table.gameEvent());
    alloc.writeByte(event);
    alloc.writeFloat(value);
    return alloc;
  }

  /**
   * Whether a raw packet is a Player Chat message that carries a signature. The client records
   * exactly these in its "last seen" window, and the server tracks them as pending
   * acknowledgements, so seamless transfers count them to keep acknowledgements valid.
   *
   * @param buf     the raw packet, readerIndex at the packet id
   * @param table   the connection's packet id table
   * @param version the connection's protocol version
   * @return true for a signed Player Chat packet
   */
  public static boolean isSignedPlayerChat(ByteBuf buf, Table table, ProtocolVersion version) {
    if (peekVarInt(buf) != table.playerChat()) {
      return false;
    }
    try {
      final ByteBuf in = buf.duplicate();
      ProtocolUtils.readVarInt(in); // packet id
      if (version.noLessThan(MINECRAFT_1_21_5)) {
        ProtocolUtils.readVarInt(in); // global index
      }
      in.skipBytes(16); // sender UUID
      ProtocolUtils.readVarInt(in); // index
      return in.readBoolean(); // signature present
    } catch (RuntimeException e) {
      return false;
    }
  }

  /**
   * Reads the leading varint (packet id) of a raw packet without consuming it.
   *
   * @param buf the raw packet, readerIndex at the packet id
   * @return the packet id, or -1 if it could not be read within 3 bytes
   */
  public static int peekVarInt(ByteBuf buf) {
    final int readerIndex = buf.readerIndex();
    int result = 0;
    for (int i = 0; i < 3; i++) {
      if (buf.writerIndex() <= readerIndex + i) {
        return -1;
      }
      final byte read = buf.getByte(readerIndex + i);
      result |= (read & 0x7F) << (7 * i);
      if ((read & 0x80) == 0) {
        return result;
      }
    }
    return -1;
  }

  private static int varIntLength(int value) {
    return value < 0x80 ? 1 : value < 0x4000 ? 2 : 3;
  }
